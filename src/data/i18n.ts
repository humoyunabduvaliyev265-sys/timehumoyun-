/**
 * Safe translation lookup with mandatory fallback to Uzbek (uz) if key is missing or undefined.
 */
export function getTranslation(lang: Language, key: keyof TranslationDictionary): string {
  const currentDict = translations[lang];
  if (currentDict && currentDict[key]) {
    return currentDict[key];
  }
  // Mandatory fallback to Uzbek if translation is missing
  const uzDict = translations['uz'];
  if (uzDict && uzDict[key]) {
    return uzDict[key];
  }
  // Secondary fallback to English if any
  const enDict = translations['en'];
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  return String(key);
}
